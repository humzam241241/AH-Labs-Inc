-- Durable catalog pricing and master-editable item records.
create table if not exists public.catalog_items (
  id uuid primary key default gen_random_uuid(),
  item_key text not null unique,
  item_type text not null check (item_type in ('card','printed')),
  category_slug text,
  product_slug text not null,
  design_number integer,
  name text not null,
  base_price_cents integer check (base_price_cents is null or base_price_cents >= 0),
  markup_percent numeric(8,2) not null default 0 check (markup_percent >= 0),
  price_cents integer check (price_cents is null or price_cents >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.catalog_items enable row level security;
revoke all on public.catalog_items from anon, authenticated;
grant select on public.catalog_items to anon, authenticated;
drop policy if exists catalog_items_public_read on public.catalog_items;
create policy catalog_items_public_read on public.catalog_items
  for select to anon, authenticated using (active = true);

